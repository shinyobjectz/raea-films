#!/bin/bash
# The thermal film for a phone held upright (thermal/tall/film.tsx, 1080x1920), with the wide film's sound.
# Each shot renders in its own process from a one-shot entry (as tools/thermal-film.sh does, for the same reason: a
# FramePass keeps its first mount's shader and textures), straight to an 80 Mbps MP4 (the PNG frames of the whole film
# are 17 GB of grain), then the shots join in order under the WAV the wide film's render left (out/thermal-film.wav),
# capped as the wide one is (20 Mbps).
#   bash tools/thermal-tall.sh [SHOT...]          -> out/thermal-tall-shots/NN.mp4, out/thermal-film-tall.mp4
#   bash tools/thermal-tall.sh stills [SHOT...]   -> out/thermal-tall-stills/NN.png (each shot at 72% of it)
#   bash tools/thermal-tall.sh check [SHOT...]    -> raea check --quick on each shot's words, for TikTok and for Reels
# Shots named re-render only those; the others keep their files.
set -euo pipefail
cd "$(dirname "$0")/.."
mode=film; [[ ${1:-} == stills || ${1:-} == check ]] && { mode=$1; shift; }
n=$(grep -c '^  { at: ' thermal/film.tsx)
list=("$@"); [ ${#list[@]} -gt 0 ] || list=($(seq 0 $((n - 1))))
shots=out/thermal-tall-shots; stills=out/thermal-tall-stills
mkdir -p "$shots" "$stills"
[[ -f out/thermal-film.wav ]] || raea render thermal-film.tsx -o out/thermal-film.wav

entry() {   # the one-shot entry for shot $1
  cat > "thermal-tall-$1.gen.tsx" <<EOF
// generated by tools/thermal-tall.sh: shot $1 of the tall thermal film alone
import { Composition, registerRoot } from "raea";
import { shotFrames } from "./thermal/film";
import { ShotOnlyT } from "./thermal/tall/film";
registerRoot(() => <Composition id="thermal-tall-$1" width={1080} height={1920} fps={30} durationInFrames={shotFrames($1).frames} component={() => <ShotOnlyT i={$1} />} />);
EOF
}
frames_of() { bun --preload ./tools/raea-stub.ts -e "import { shotFrames } from './thermal/film'; console.log(shotFrames($1).frames)"; }

for i in "${list[@]}"; do
  nn=$(printf %02d "$i")
  entry "$i"
  trap 'rm -f thermal-tall-*.gen.tsx' EXIT
  if [[ $mode == check ]]; then
    for p in tiktok reels; do
      echo "== shot $nn, $p"
      raea check "thermal-tall-$i.gen.tsx" --quick --platform "$p" 2>&1 | grep -v "^$" | head -12 || true
    done
  elif [[ $mode == stills ]]; then
    at=$(( $(frames_of "$i") * ${PCT:-72} / 100 ))
    d=$stills/$nn.d; rm -rf "${d:?}"; mkdir -p "$d"
    if raea render "thermal-tall-$i.gen.tsx" --at "$at" -o "$d/" > "$d.log" 2>&1; then
      mv "$(ls "$d"/*.png | head -1)" "$stills/$nn.png"; rm -rf "${d:?}" "$d.log"; echo "still $nn (frame $at)"
    else echo "FAIL still $nn"; grep -E "REFUSED|rror" "$d.log" | cut -c1-240 | head -4; fi
  else
    if raea render "thermal-tall-$i.gen.tsx" --kbps 80000 -o "$shots/$nn.mp4" > "$shots/$nn.log" 2>&1; then
      echo "shot $nn: $(ffprobe -v error -select_streams v -count_packets -show_entries stream=nb_read_packets -of csv=p=0 "$shots/$nn.mp4") frames"
    else echo "FAIL shot $nn"; grep -E "REFUSED|rror" "$shots/$nn.log" | cut -c1-240 | head -4; exit 1; fi
  fi
  rm -f "thermal-tall-$i.gen.tsx"
done
[[ $mode == film ]] || exit 0

# every shot in order, counted against the sound
k=0; : > "$shots/list.txt"
for i in $(seq 0 $((n - 1))); do
  f=$shots/$(printf %02d "$i").mp4
  [[ -f $f ]] || { echo "thermal-tall: shot $i is missing" >&2; exit 1; }
  echo "file '$(basename "$f")'" >> "$shots/list.txt"
  k=$((k + $(ffprobe -v error -select_streams v -count_packets -show_entries stream=nb_read_packets -of csv=p=0 "$f")))
done
want=$(ffprobe -v error -show_entries format=duration -of csv=p=0 out/thermal-film.wav | awk '{ printf "%d", $1 * 30 + 0.5 }')
echo "frames: $k (the sound is $want)"
[ $((k - want)) -le 1 ] && [ $((want - k)) -le 1 ] || { echo "thermal-tall: the shots' frames don't add up to the film" >&2; exit 1; }
ffmpeg -v error -nostdin -y -f concat -safe 0 -i "$shots/list.txt" -i out/thermal-film.wav \
  -map 0:v -map 1:a -c:v libx264 -preset slow -crf 17 -maxrate 20M -bufsize 40M -pix_fmt yuv420p \
  -colorspace bt709 -color_primaries bt709 -color_trc bt709 -color_range tv -r 30 \
  -movflags +faststart -c:a aac -b:a 256k -shortest out/thermal-film-tall.mp4
ffprobe -v error -show_entries stream=width,height,nb_frames:format=duration,bit_rate -of default=nw=1 out/thermal-film-tall.mp4
ffmpeg -v info -nostdin -i out/thermal-film-tall.mp4 -af ebur128=peak=true -f null - 2>&1 | grep -E "I:|Peak:" | tail -2
