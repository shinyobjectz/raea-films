#!/bin/bash
# The thermal film: its sound (score, voice, effects, mixed to -14 LUFS by <Mix>) rendered whole as a WAV; its picture
# rendered a shot at a time as PNG frames, each shot in its own process from a one-shot entry (thermal/film.tsx
# ShotOnly: in one render a FramePass keeps its first mount's shader and depth textures, so no later shot was traced);
# then the frames in order, muxed under X's 512 MB cap (the moving grain asks for ~86 Mbps uncapped: 20 Mbps ceiling).
# Run from the project: tools/thermal-film.sh [OUT.mp4] [SHOT...]   (shots named re-render only those; the rest keep their frames)
set -euo pipefail
cd "$(dirname "$0")/.."
out=${1:-out/thermal-film.mp4}
shots=out/thermal-shots
frames=out/thermal-film
entry=thermal-shot.gen.tsx
n=$(grep -c '^  { at: ' thermal/film.tsx)
shift || true
list=("$@"); [ ${#list[@]} -gt 0 ] || list=($(seq 0 $((n - 1))))
trap 'rm -f "$entry"' EXIT

raea render thermal-film.tsx -o out/thermal-film.wav
for i in "${list[@]}"; do
  cat > "$entry" <<EOF
// generated by tools/thermal-film.sh: shot $i of the thermal film alone
import { Composition, registerRoot } from "raea";
import { ShotOnly, shotFrames } from "./thermal/film";
registerRoot(() => <Composition id="thermal-shot-$i" width={1920} height={1080} fps={30} durationInFrames={shotFrames($i).frames} component={() => <ShotOnly i={$i} />} />);
EOF
  d=$shots/$(printf %02d "$i")
  rm -rf "${d:?}" && mkdir -p "$d"
  raea render "$entry" -o "$d/" 2>&1 | grep -E "error|raea render:" || true
  echo "shot $i: $(ls "$d" | grep -c '^frame-') frames"
done

# every shot's frames, in order, numbered through the film
rm -rf "${frames:?}" && mkdir -p "$frames"
k=0
for d in "$shots"/[0-9][0-9]; do
  for f in "$d"/frame-*.png; do
    ln "$f" "$frames/$(printf 'frame-%05d.png' "$k")"
    k=$((k + 1))
  done
done
want=$(ffprobe -v error -show_entries format=duration -of csv=p=0 out/thermal-film.wav | awk '{ printf "%d", $1 * 30 + 0.5 }')
echo "frames: $k (the sound is $want)"
[ $((k - want)) -le 1 ] && [ $((want - k)) -le 1 ] || { echo "thermal-film: the shots' frames don't add up to the film" >&2; exit 1; }
ffmpeg -v error -y -framerate 30 -i "$frames/frame-%05d.png" -i out/thermal-film.wav \
  -map 0:v -map 1:a -c:v libx264 -preset slow -crf 17 -maxrate 20M -bufsize 40M -pix_fmt yuv420p -movflags +faststart \
  -c:a aac -b:a 256k -shortest "$out"
ffprobe -v error -show_entries format=duration,bit_rate -of default=nw=1 "$out"
ffmpeg -v info -i "$out" -af ebur128=peak=true -f null - 2>&1 | grep -E "I:|Peak:" | tail -2
