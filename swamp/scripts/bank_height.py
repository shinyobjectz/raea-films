# The scanned bank's real top: the height of the highest surface over each point of a grid round the pit, from the
# root_cluster glTFs as world.tsx places them (position, Euler XYZ rotation, scale). Writes a TS module.
import sys, json, struct, math, numpy as np
gl_path, out_path = sys.argv[1], sys.argv[2]
g = json.load(open(gl_path))
import os
base = os.path.dirname(gl_path)
bufs = [open(os.path.join(base, b['uri']), 'rb').read() for b in g['buffers']]
CT = {5126: ('f', 4), 5123: ('H', 2), 5125: ('I', 4), 5121: ('B', 1)}
NC = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4}
def acc(i):
    a = g['accessors'][i]; bv = g['bufferViews'][a['bufferView']]
    fmt, sz = CT[a['componentType']]; n = NC[a['type']]
    off = bv.get('byteOffset', 0) + a.get('byteOffset', 0)
    stride = bv.get('byteStride', sz * n)
    raw = bufs[bv['buffer']]
    dt = np.dtype('<' + fmt)
    if stride == sz * n:
        return np.frombuffer(raw, dtype=dt, count=a['count'] * n, offset=off).reshape(a['count'], n).astype(np.float64)
    return np.array([struct.unpack_from('<' + fmt * n, raw, off + k * stride) for k in range(a['count'])], dtype=np.float64)
def qmat(q):
    x, y, z, w = q
    return np.array([[1-2*(y*y+z*z), 2*(x*y-z*w), 2*(x*z+y*w)], [2*(x*y+z*w), 1-2*(x*x+z*z), 2*(y*z-x*w)], [2*(x*z-y*w), 2*(y*z+x*w), 1-2*(x*x+y*y)]])
def nodemat(n):
    M = np.eye(4)
    if 'matrix' in n: return np.array(n['matrix']).reshape(4, 4).T
    T = np.eye(4); T[:3, 3] = n.get('translation', [0, 0, 0])
    R = np.eye(4); R[:3, :3] = qmat(n.get('rotation', [0, 0, 0, 1]))
    S = np.diag(list(n.get('scale', [1, 1, 1])) + [1])
    return T @ R @ S
tris_local = []
def walk(ni, M):
    n = g['nodes'][ni]; M = M @ nodemat(n)
    if 'mesh' in n:
        for p in g['meshes'][n['mesh']]['primitives']:
            P = acc(p['attributes']['POSITION'])
            I = acc(p['indices']).astype(np.int64).reshape(-1, 3) if 'indices' in p else np.arange(len(P)).reshape(-1, 3)
            Pw = (M @ np.c_[P, np.ones(len(P))].T).T[:, :3]
            tris_local.append(Pw[I])
    for c in n.get('children', []): walk(c, M)
for ni in g['scenes'][g.get('scene', 0)]['nodes']: walk(ni, np.eye(4))
TL = np.concatenate(tris_local)
def euler_xyz(r):
    cx, sx, cy, sy, cz, sz = math.cos(r[0]), math.sin(r[0]), math.cos(r[1]), math.sin(r[1]), math.cos(r[2]), math.sin(r[2])
    Rx = np.array([[1,0,0],[0,cx,-sx],[0,sx,cx]]); Ry = np.array([[cy,0,sy],[0,1,0],[-sy,0,cy]]); Rz = np.array([[cz,-sz,0],[sz,cz,0],[0,0,1]])
    return Rx @ Ry @ Rz
PLACES = [((0.25, -0.36, 3.45), (0, 0.15, 0), (1.75, 0.42, 1.7)), ((0.3, -0.39, 4.0), (0, 3.3, 0), (0.8, 0.42, 0.47))]
X0, X1, Z0, Z1, D = -2.1, -0.5, 1.9, 3.5, 0.02
xs = np.arange(X0, X1 + 1e-9, D); zs = np.arange(Z0, Z1 + 1e-9, D)
H = np.full((len(zs), len(xs)), -0.02)
for p, r, s in PLACES:
    T = TL * np.array(s); T = T @ euler_xyz(r).T; T = T + np.array(p)
    # only triangles over the grid
    mn = T.min(1); mx = T.max(1)
    keep = (mx[:, 0] >= X0) & (mn[:, 0] <= X1) & (mx[:, 2] >= Z0) & (mn[:, 2] <= Z1)
    for a, b, c in T[keep]:
        x0, x1 = min(a[0], b[0], c[0]), max(a[0], b[0], c[0]); z0, z1 = min(a[2], b[2], c[2]), max(a[2], b[2], c[2])
        i0, i1 = max(0, int(math.ceil((x0 - X0) / D))), min(len(xs) - 1, int(math.floor((x1 - X0) / D)))
        j0, j1 = max(0, int(math.ceil((z0 - Z0) / D))), min(len(zs) - 1, int(math.floor((z1 - Z0) / D)))
        if i1 < i0 or j1 < j0: continue
        gx, gz = np.meshgrid(xs[i0:i1+1], zs[j0:j1+1])
        v0 = (b[0]-a[0], b[2]-a[2]); v1 = (c[0]-a[0], c[2]-a[2])
        den = v0[0]*v1[1] - v1[0]*v0[1]
        if abs(den) < 1e-12: continue
        px, pz = gx - a[0], gz - a[2]
        u = (px*v1[1] - v1[0]*pz) / den; v = (v0[0]*pz - px*v0[1]) / den
        inside = (u >= -1e-9) & (v >= -1e-9) & (u + v <= 1 + 1e-9)
        y = a[1] + u*(b[1]-a[1]) + v*(c[1]-a[1])
        sub = H[j0:j1+1, i0:i1+1]
        H[j0:j1+1, i0:i1+1] = np.where(inside, np.maximum(sub, y), sub)
bank = lambda x, z: 0.24 - 0.09 * math.pow(math.hypot((x - 0.25) / 2.6, (z - 3.55) / 1.3), 2.5)
for (x, z) in [(-1.3, 2.7), (-1.0, 2.7), (-1.6, 2.7), (-1.3, 2.4), (-1.3, 3.0), (-1.55, 2.95), (-1.05, 2.45)]:
    i, j = int(round((x - X0) / D)), int(round((z - Z0) / D))
    print(f"({x},{z}) real {H[j,i]:.3f} formula {bank(x,z):.3f}")
vals = ",".join(f"{v:.3f}".rstrip('0').rstrip('.') if v != 0 else "0" for v in H.flatten())
open(out_path, 'w').write(f"""// GENERATED by scripts/bank_height.py: the scanned bank's real top round the pit (the highest surface over each
// point of a {D * 100:.0f} cm grid, from root_cluster_01 as world.tsx places it twice), -0.02 (the water) where there's none.
export const BANK_GRID = {{ x0: {X0}, z0: {Z0}, d: {D}, nx: {len(xs)}, nz: {len(zs)} }};
const H = [{vals}];
/** the bank's top at (x, z), bilinear; outside the grid, undefined */
export const bankAt = (x: number, z: number): number | undefined => {{
  const {{ x0, z0, d, nx, nz }} = BANK_GRID;
  const fx = (x - x0) / d, fz = (z - z0) / d;
  if (fx < 0 || fz < 0 || fx > nx - 1 || fz > nz - 1) return undefined;
  const i = Math.min(nx - 2, Math.floor(fx)), j = Math.min(nz - 2, Math.floor(fz)), u = fx - i, v = fz - j;
  const h = (a: number, b: number) => H[b * nx + a];
  return (h(i, j) * (1 - u) + h(i + 1, j) * u) * (1 - v) + (h(i, j + 1) * (1 - u) + h(i + 1, j + 1) * u) * v;
}};
""")
print("tris", len(TL), "grid", H.shape, "min", H.min(), "max", H.max())
