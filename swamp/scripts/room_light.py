# The review room screen's light: for every picture the screen shows (assets/room/screen), the mean linear colour of
# each tile of a TX x TY grid over it. room.tsx puts a glowing tile behind the screen for each, which Solari traces, so
# the room takes the film's light frame by frame. (A plane with the picture as its emissive texture did this in a still,
# but raea's video path never shows a material's texture first used partway through a shot, and the picture changes
# every frame: emissive colours do change in a video.)
#
# usage: python -I scripts/room_light.py SCREEN_DIR OUT.ts
#   SCREEN_DIR  assets/room/screen (scripts/room_screen.py's frames)
#   OUT.ts      components/room-light.ts
import os
import sys

import numpy as np
from PIL import Image

src, out_ts = sys.argv[1:3]
TX, TY = 8, 5


def srgb_to_linear(c):
    c = c / 255.0
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


# (v5: not the close shot's typing frames, type-*: 30b-glyphs lights by note-draft's light, as it always has, room.tsx)
names = sorted(n[:-4] for n in os.listdir(src) if n.endswith(".jpg") and not n.startswith("type-"))
light = {}
for n in names:
    lin = srgb_to_linear(np.asarray(Image.open(os.path.join(src, n + ".jpg")).convert("RGB"), np.float64))
    h, w = lin.shape[:2]
    t = [lin[(y * h) // TY : ((y + 1) * h) // TY, (x * w) // TX : ((x + 1) * w) // TX].reshape(-1, 3).mean(0) for y in range(TY) for x in range(TX)]
    light[n] = np.concatenate(t)

with open(out_ts, "w") as f:
    f.write("// Generated by scripts/room_light.py: the review room screen's light, each picture's mean linear rgb on a grid of\n")
    f.write("// tiles, row by row from the top.\n")
    f.write(f"export const LIGHT_GRID = {{ x: {TX}, y: {TY} }};\n")
    f.write("export const LIGHT: Record<string, number[]> = {\n")
    for n in names:
        f.write(f'  "{n}": [{", ".join(f"{v:.4g}" for v in light[n])}],\n')
    f.write("};\n")
print("pictures", len(names))
