// 03 Start the project (1): + in the rail, the name typed, the goose emoji searched and picked, Make project.
import { cap, chapter, click, hover, key, move, node, pause, tap, text, tip, typeInto, vis, d } from "./tk.mjs"
chapter("03")
await hover("new-project", 0, { steps: 5 })
await tip()
await cap("050-plus-hover", "Pointer on the rail's + (New project): its tip")
await click("new-project")
await node("project-name")
await d.wait("the title's focus", async () => vis(await d.ui(), "project-name")?.focused)
await move(800, 300, 2)
await cap("051-new-project", "The peck: the New project dialog (Title, Description, Icon), Title focused and empty")
await typeInto("project-name", "Swamp Goose", { every: 4, name: "052-name", about: "Title typed" })
await hover("project-mark", 0, { steps: 3 })
await cap("053-icon-hover", "Pointer on Icon (First letter, colour 5)")
await click("project-mark")
await node("project-mark-emoji3d")
await cap("054-icon-open", "Icon open: eight colours, Search emoji, and the emoji grid")
const g = (await node("project-mark-emoji3d")).rect
await tap(g.x + 216, g.y + 16, "emoji-search")
await typeInto("project-mark-emoji3d", "goose", {})
await pause(1200)
await cap("055-search-goose", "Search emoji: \"goose\" typed, the goose found")
const g2 = (await node("project-mark-emoji3d")).rect
await move(g2.x + 18, g2.y + 58, 3)
await tip()
await cap("056-goose-hover", "Pointer on the goose")
await tap(g2.x + 18, g2.y + 58, "emoji-goose")
await pause(600)
await cap("057-goose-picked", "The goose picked: the Icon row shows it")
await hover("make-project", 0, { steps: 4 })
await cap("058-make-hover", "Pointer on Make project")
await click("make-project")
await d.wait("the project in the rail", async () => (await d.ui()).nodes.some((n) => n.visible && /^project-/.test(n.id) && /Swamp Goose/.test(n.name ?? "")), 30000)
await node("feed-empty")
await move(420, 260, 4)
await cap("059-project-made", "Swamp Goose made and open: the goose in the rail, its empty chat and feed")
const tile = (await d.ui()).nodes.find((n) => n.visible && /^project-/.test(n.id) && /Swamp Goose/.test(n.name ?? ""))
console.log("tile", tile.id, JSON.stringify(tile.rect))
await hover(tile.id, 0, { steps: 4 })
await tip()
await cap("060-goose-tile", "Pointer on Swamp Goose's tile: the goose (the font's goose; no 3D goose in the library, so it doesn't turn)")
