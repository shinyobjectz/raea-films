// 03 Start the project (2, from the line typed on): the AI picked (Kimi, the take's stand-in, the one signed in here), the line typed and sent,
// the agent's answer with its running job folded over the box and Stop, then /goal: "honk" typed and deleted, the real
// condition set, and the goal over the composer. The agent's job holds at its "build" gate (04 releases it).
import { cap, chapter, click, hover, key, mark, move, node, pause, text, tip, typeInto, vis, d } from "./tk.mjs"
chapter("03")
const box = async () => (await d.ui()).nodes.find((n) => n.visible && /^Message/.test(n.name ?? "") && /input$/.test(n.id))
// (061, 062: Kimi picked, captured on the first run)
const b0 = await box()
await click(b0.id)
await typeInto(b0.id, "make me a music video. me, in a swamp, summoning ancient magic", { every: 16, name: "063-prompt", about: "The line typed into the chat's box" })
await hover("new-chat-send", 0, { steps: 3 })
await cap("064-send-hover", "Pointer on Send")
await key("Enter")
await mark("running", 60000)
await pause(1500)
await move(700, 520, 3)
await cap("065-answer-running", "Sent: the line in the chat, the agent's answer arriving, its job running, folded over the box")
const u = await d.ui()
for (const n of u.nodes) if (n.visible && (/stop|running|work-/i.test(n.id) || /Stop/.test(n.name ?? ""))) console.log("node", d.fmt(n))
const stop = u.nodes.find((n) => n.visible && /stop/i.test(n.id) && n.rect.y > 600)
if (stop) { await hover(stop.id, 0, { steps: 3 }); await tip(); await cap("066-stop-hover", "Pointer on Stop, beside Send, while the job runs") }
// /goal: honk first, deleted, then the condition
const b1 = await box()
await click(b1.id)
await text("/")
await pause(700)
await cap("067-slash", "/ typed in the box: raea's commands, /goal first")
await typeInto(b1.id, "goal honk", {})
await pause(400)
await cap("068-goal-honk", "\"/goal honk\" typed")
for (let i = 0; i < 10; i++) { await key("Backspace"); await pause(90); if (i === 4) await cap("069-goal-deleting", "Deleting it, a letter at a time") }
await pause(300)
await cap("070-goal-gone", "Gone: the box empty again")
await typeInto(b1.id, "/goal every shot has me in it", { every: 15, name: "071-goal", about: "The goal typed" })
await key("Enter")
await pause(2500)
await move(700, 560, 3)
await cap("072-goal-set", "The goal set: its line over the composer, over the running job")
const u2 = await d.ui()
for (const n of u2.nodes) if (n.visible && /goal|work-/i.test(n.id + " " + (n.name ?? ""))) console.log("node", d.fmt(n))
