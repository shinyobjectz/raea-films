// 03 Start the project (2), in one run (the re-take of 11-16): Pick an AI (Kimi, the take's stand-in), the line typed
// and sent, the agent's answer with its job running, Stop, then /goal: "honk" typed and deleted, the real condition
// set. The agent's job holds at its "build" gate (04 releases it).
import { cap, chapter, click, hover, key, mark, move, node, pause, text, tip, typeInto, vis, d } from "./tk.mjs"
chapter("03")
const box = async () => (await d.ui()).nodes.find((n) => n.visible && /^Message/.test(n.name ?? "") && /input$/.test(n.id))
if (!vis(await d.ui(), "new-chat-on-menu")) await click("new-chat-on")
await node("new-chat-on-kimi")
await hover("new-chat-on-kimi", 0, { steps: 3 })
await cap("061-pick-ai", "Pick an AI open under the box: Kimi, the only AI signed in on this scratch Mac (the take's stand-in), pointer on it")
await click("new-chat-on-kimi")
await pause(600)
await cap("062-ai-picked", "Kimi picked: the box is ready")
const b0 = await d.wait("the box", box, 15000)
await click(b0.id)
await typeInto(b0.id, "make me a music video. me, in a swamp, summoning ancient magic", { every: 16, name: "063-prompt", about: "The line typed into the chat's box" })
await hover("new-chat-send", 0, { steps: 3 })
await cap("064-send-hover", "Pointer on Send")
await key("Enter")
await mark("running", 60000)
await pause(1500)
await move(700, 520, 3)
await cap("065-answer-running", "Sent: the line in the chat, the agent's answer arriving, its job running, folded over the box")
await node("agent-send")
await hover("agent-send", 0, { steps: 4 })
await tip()
await cap("066-stop-hover", "Pointer on Stop, in Send's place while the job runs (1 running folded over the box)")
await click("agent-prompt")
await text("/")
await pause(800)
await cap("067-slash", "/ typed in the box: raea's commands, /goal first")
await typeInto("agent-prompt", "goal honk", {})
await pause(500)
await cap("068-goal-honk", "\"/goal honk\" typed")
for (let i = 0; i < 10; i++) { await key("Backspace"); await pause(110); if (i === 4) await cap("069-goal-deleting", "Deleting it, a letter at a time", { live: true }) }
await pause(400)
await cap("070-goal-gone", "Gone: the box empty again")
await typeInto("agent-prompt", "/goal every shot has me in it", { every: 15, name: "071-goal", about: "The goal typed" })
await pause(500)
await key("Enter")
await pause(3000)
await move(700, 560, 3)
await cap("072-goal-set", "The goal set: its line over the composer, with the running job")
