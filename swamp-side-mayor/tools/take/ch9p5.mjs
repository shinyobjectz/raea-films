// the sent note's turn: its bottom edge against the chat's top (under its 48-pixel bar); clean when it's above it
const wall = async (tag) => {
  const u = await d.ui()
  const users = u.nodes.filter((n) => /^turn-user-\d+$/.test(n.id)).sort((a, b) => Number(b.id.split("-")[2]) - Number(a.id.split("-")[2]))
  const w = users[0], bottom = w ? w.rect.y + w.rect.h : -1, clean = bottom <= 48
  console.log(`  ${tag}: the note's turn ends at y ${Math.round(bottom)} (${clean ? "out of view" : "STILL IN VIEW"})`)
  return clean
}
const capClean = async (tag, name, about, o) => { if (await wall(tag)) await cap(name, about, o); else console.log(`  skipped ${name}`) }
