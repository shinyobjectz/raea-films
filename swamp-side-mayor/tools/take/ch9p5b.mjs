const s = (await d.ui()).nodes.find((n) => n.visible && /^bar-send-edits|^send-notes|^notes-send/.test(n.id))
if (!s) throw new Error("no send-notes after posting")
const sx = s.rect.x + s.rect.w / 2, sy = s.rect.y + s.rect.h / 2
await move(sx, sy, 4)
await pause(500)
await cap("233-send-hover", "Pointer on Send (1 note waiting)")
await tap(sx, sy, "send-notes")
await mark("note-planned", 60000)
await pause(2500)
await move(700, 500, 3)
await cap("234-note-sent", "Sent: the note in the chat, the agent taking it, its task made")
