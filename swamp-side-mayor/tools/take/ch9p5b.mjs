import { cap, chapter, click, go, hover, key, mark, move, node, pause, tap, tip, d } from "./tk.mjs"
chapter("v9-05b")
const show = async (re) => { const u = await d.ui(); for (const n of u.nodes) if (n.visible && re.test(n.id + " " + (n.name ?? ""))) console.log("n", d.fmt(n), JSON.stringify(String(n.text ?? n.value ?? "").slice(0, 80))) }
if ((await d.ui()).nodes.some((n) => n.visible && n.id === "inline-input")) { await click("inline-input"); await pause(400); await key("End"); await key("Enter"); await pause(1500) }
await move(1250, 300, 3)
await pause(500)
await show(/send|^comment-|note-/)
