// 01 The map: the rail and its projects (each emoji turning to the pointer), the duck, a project opened to its chat
// with the panel on its feed, and Command-backslash hiding the panel and bringing it back.
import { cap, chapter, click, hover, key, move, node, pause, tip, vis, d } from "./tk.mjs"
chapter("01")
await click("rail-home")
await node("inbox-empty")
await move(820, 470)
await cap("010-everything", "The app on Everything: the rail down the left (workspace, Everything, Search, four projects, New project; Publish, Connections, Settings and the account at its foot), the workspace's chat, the panel on the Inbox. Pointer mid-window")
// the head tracking: the pointer goes where Goose looks, sweeping past the rail's emoji (each turns toward it)
await move(300, 160, 6)
await cap("011-look-up-left", "Pointer up and left, near the rail: the projects' 3D emoji turn toward it")
await move(160, 470, 6)
await cap("012-look-down", "Pointer lower, nearer the rail's foot: the emoji tilt to follow")
await hover("project-night-shift-trailer", 0, { steps: 4 })
await tip()
await cap("013-hover-night-shift", "Pointer on Night Shift Trailer's tile: its name in the rail's tip")
await hover("project-bakery-reel", 0, { steps: 3 })
await tip()
await cap("014-hover-bakery", "Pointer on Bakery Reel")
await hover("project-rubber-duck-ad", 0, { steps: 3 })
await tip()
await cap("015-hover-duck", "Pointer resting on the duck: Rubber Duck Ad. Its mark is the font's duck (the 3D library has no duck), so it doesn't turn; the others do")
await move(340, 300, 4)
await cap("016-duck-from-right", "Pointer off to the right of the rail: the 3D emoji face it, the duck stays as it was")
await hover("project-night-shift-trailer", 0, { steps: 4 })
await d.input({ type: "down", x: (await node("project-night-shift-trailer")).rect.x + 22, y: (await node("project-night-shift-trailer")).rect.y + 22, button: "left", clicks: 1 })
await d.input({ type: "up", x: (await node("project-night-shift-trailer")).rect.x + 22, y: (await node("project-night-shift-trailer")).rect.y + 22, button: "left", clicks: 1 })
await node("feed-empty")
await move(600, 300, 4)
await cap("017-project-open", "Night Shift Trailer opened (the peck): its chat on the left (What should we make?), its panel on the right open on Feed (its feed is empty: everything agents make for this project lands here)")
await move(600, 790, 4)
await cap("018-chat-box", "Pointer on the chat's box: Pick an AI under it, where you talk to the project's agent")
await move(1370, 380, 4)
await cap("019-panel-feed", "Pointer over the panel, open on its Feed tab")
await key("\\", ["meta"])
await d.wait("the panel hidden", async () => !vis(await d.ui(), "shell-panel"))
await cap("020-panel-hidden", "Command-backslash: the panel hidden, the chat the whole width")
await key("\\", ["meta"])
await node("shell-panel")
await cap("021-panel-back", "Command-backslash again: the panel back, on Feed")
